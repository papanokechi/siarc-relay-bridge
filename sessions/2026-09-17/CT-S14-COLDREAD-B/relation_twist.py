import sympy as sp

z, x, lam = sp.symbols('z x lam')
rB = (11*z**4 + 4*z**2 + 4*z + 12)/(4*z**4*(z**2 + z + 3)**2)
A = 3*x**2 + x + 1
B = 6*x + 1
C = -x**2
P_C = sp.simplify(B/A)
Q_C = sp.simplify(C/A)
rC = sp.simplify(sp.diff(P_C, x)/2 + P_C**2/4 - Q_C)
rB_inv = sp.simplify(rB.subs(z, 1/x)/x**4)

print('Companion page-image polynomial data used:')
print('  a(x) =', A)
print('  b(x) =', B)
print('  c(x) =', C)
print('  equation: a(x)y\'\' + b(x)y\' + c(x)y = 0')
print()
print('Normal-form comparison under z = 1/x:')
print('  r_C(x) = P_C\'/2 + P_C^2/4 - Q_C =', sp.factor(rC))
print('  r_B(1/x)/x^4 =', sp.factor(rB_inv))
print('  difference =', sp.factor(sp.together(rC - rB_inv)))
print()
print('Coordinate pullback of B gives Y\'\' + (2/x)Y\' - r_B(1/x)/x^4 Y = 0.')
print('Putting U = x*Y gives the trace-free normal form U\'\' = r_B(1/x)/x^4 U.')
print('The companion equation is obtained from U by U = sqrt(A)*W, i.e. W = A^(-1/2) U.')
f = sp.sqrt(A)
P_from_twist = sp.simplify(2*sp.diff(f, x)/f)
Q_from_twist = sp.simplify(sp.diff(f, x, 2)/f - rB_inv)
print('  2 f\'/f - P_C =', sp.simplify(P_from_twist - P_C))
print('  f\'\'/f - r_B(1/x)/x^4 - Q_C =', sp.factor(sp.together(Q_from_twist - Q_C)))
print('  trace of trace-free normal system = 0')
print('  trace after rank-1 twist W=A^(-1/2)U is -P_C =', sp.factor(-P_C))
print('  trace change = -dlog(A) =', sp.factor(-sp.diff(A, x)/A))
print()
print('Integer-difference points under the twist:')
for beta in sp.solve(A, x):
    p_res = sp.simplify(sp.limit((x-beta)*P_C, x, beta))
    q_t2 = sp.simplify(sp.limit((x-beta)**2*Q_C, x, beta))
    q_t1 = sp.simplify(sp.limit((x-beta)*Q_C, x, beta))
    indicial = sp.factor(lam*(lam-1) + p_res*lam + q_t2)
    print('  beta =', beta)
    print('    residue_P =', p_res)
    print('    limit_(x-beta)^2_Q =', q_t2)
    print('    limit_(x-beta)_Q =', q_t1)
    print('    indicial_polynomial =', indicial)
    print('    exponents_after_twist = [0, 0]')
    print('    ordinary_after_twist = False (P_C has nonzero simple-pole residue)')

def main() -> int:
    if CLAIMS.exists() and CLAIMS.read_text(encoding="utf-8").strip():
        print(f"refusing to overwrite a non-empty {CLAIMS.name}")
        return 2
    with open(CLAIMS, "w", encoding="utf-8", newline="\n") as fh:
        for r in ROWS:
            fh.write(json.dumps(r, ensure_ascii=True) + "\n")

    back = [json.loads(l) for l in CLAIMS.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(back) == len(ROWS), "read-back: row count differs"
    for r in back:
        assert r["output_hash"] and len(r["output_hash"]) == 64, f"{r['claim_id']}: bad hash"
        src = [k for k, v in H.items() if v == r["output_hash"]]
        assert src, f"{r['claim_id']}: hash matches no artefact"
    print(f"wrote {len(back)} claims to {CLAIMS.name}, read back and verified")
    for k, v in FILES.items():
        print(f"  {v.name:<28} sha256 {H[k]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

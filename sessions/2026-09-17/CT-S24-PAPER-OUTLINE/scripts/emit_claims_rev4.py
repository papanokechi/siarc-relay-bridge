def load():
    rows = []
    for line in CLAIMS.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def write(rows):
    with open(CLAIMS, "w", encoding="utf-8", newline="\n") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=True) + "\n")


def main() -> int:
    rows = load()
    existing = {r["claim_id"] for r in rows}
    print(f"claims.jsonl before: {len(rows)} rows")

    # hashes the earlier claims cite, recorded BEFORE anything is written
    h_rev1_before = sha256(OUT_REV1)
    h_rev3_before = sha256(OUT_REV3)
    cited_before = {r["output_hash"] for r in rows if r.get("output_hash")}
    assert h_rev1_before in cited_before, "revision-1 artefact already fails to resolve"
    assert h_rev3_before in cited_before, "revision-3 artefact already fails to resolve"
    print(f"pre-check: {OUT_REV1.name} {h_rev1_before[:8]} resolves")
    print(f"pre-check: {OUT_REV3.name} {h_rev3_before[:8]} resolves")

    # ---- phase 1: append with a null hash ------------------------------
    for c in CLAIMS_REV4:
        if c["claim_id"] in existing:
            print(f"  {c['claim_id']}: already present, refusing to duplicate")
            return 2
        rows.append(c)
    write(rows)
    print(f"phase 1: appended {len(CLAIMS_REV4)} claims with output_hash = null")

    # ---- phase 2: run the checker to its FINAL path, then hash ---------
    print(f"phase 2: running verify_outline.py -> {OUT_REV4.name}")
    with open(OUT_REV4, "w", encoding="utf-8") as fh:
        rc = subprocess.run(
            [sys.executable, str(HERE / "verify_outline.py")],
            stdout=fh, stderr=subprocess.STDOUT, cwd=str(SESSION),
        ).returncode
    tail = OUT_REV4.read_text(encoding="utf-8").strip().splitlines()[-1]
    print(f"         checker exit {rc}; last line: {tail}")
    if rc != 0:
        print("FAIL: checker reports defects; hashes NOT written")
        return 1

    h_rev4 = sha256(OUT_REV4)
    print(f"         {OUT_REV4.name} sha256 {h_rev4}")

    # ---- phase 3: write hashes, then read back and assert --------------
    rows = load()
    for r in rows:
        if r["claim_id"] in NEW_IDS:
            r["output_hash"] = h_rev4
    write(rows)

    back = {r["claim_id"]: r for r in load()}
    bad = [i for i in NEW_IDS if not back.get(i, {}).get("output_hash")]
    assert not bad, f"read-back: claims still carrying a null hash: {bad}"
    for i in NEW_IDS:
        assert back[i]["output_hash"] == h_rev4, f"{i} carries the wrong hash"

    # the earlier artefacts must be byte-unchanged and still resolve
    assert sha256(OUT_REV1) == h_rev1_before, "revision-1 output was modified"
    assert sha256(OUT_REV3) == h_rev3_before, "revision-3 output was modified"
    cited_after = {r["output_hash"] for r in load() if r.get("output_hash")}
    assert h_rev1_before in cited_after and h_rev3_before in cited_after
    print("phase 3: revision-1 and revision-3 artefacts unchanged and still resolve: OK")

    print(f"claims.jsonl after: {len(back)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
